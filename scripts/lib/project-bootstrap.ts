import { dirname, join, resolve } from 'node:path';
import type {
  CreateProjectInput,
  IssuedProjectToken,
  ProjectPublicView,
  ProjectTemplateId,
} from '../../packages/contracts/src/projects.js';
import {
  PROJECT_TEMPLATE_PRESETS,
  validateProjectId,
} from '../../packages/core/src/projects.js';

export interface ProjectBootstrapManifest {
  id: string;
  name: string;
  description?: string;
  template: ProjectTemplateId;
  repositories: string[];
  autoMerge?: boolean;
  budgetUsd?: number;
  maxJobUsd?: number;
  regions?: string[];
  hfAutoPublishPrefixes?: string[];
  s3ArtifactPrefixes?: string[];
  protectedPaths?: string[];
  branchPrefix?: string;
  notificationChannel?: string | null;
  trigger?: {
    enabledByDefault?: false;
    provider?: 'codex' | 'claude';
    baseBranch?: string;
    intervalMinutes?: number;
    title?: string;
    instructions?: string;
    testCommand?: string[];
  };
}

export interface ProjectBootstrapOptions {
  manifest: ProjectBootstrapManifest;
  apiUrl: string;
  operatorToken: string;
  tokenOutputFile: string;
  issueToken: boolean;
  rotateToken: boolean;
  withTrigger: boolean;
  targetDir?: string;
  hivemindRoot: string;
  force: boolean;
  dryRun: boolean;
}

export interface ProjectBootstrapStepResult {
  step: string;
  status: 'done' | 'skipped' | 'planned' | 'warning' | 'failed';
  detail: string;
}

export interface ProjectBootstrapSystem {
  fetchImpl?: typeof fetch;
  fileExists(path: string): boolean;
  readFile(path: string): string;
  writeFile(path: string, content: string): void;
  writeSecretFile(path: string, content: string): void;
}

export function buildCreateProjectPayload(manifest: ProjectBootstrapManifest): CreateProjectInput {
  const id = validateProjectId(manifest.id);
  const preset = PROJECT_TEMPLATE_PRESETS[manifest.template];
  const computeBudgetCapMicros =
    manifest.budgetUsd !== undefined ? Math.round(manifest.budgetUsd * 1_000_000) : preset.budget.computeBudgetCapMicros;
  const maxSingleJobCostMicros =
    manifest.maxJobUsd !== undefined ? Math.round(manifest.maxJobUsd * 1_000_000) : preset.budget.maxSingleJobCostMicros;
  const repositories = [...new Set(manifest.repositories)];
  const autoMergeRepositories = manifest.autoMerge ? repositories : [];
  const defaultPrefixes = [
    `projects/${id}/`,
    ...(preset.compute.includeLegacyModelsPrefix ? ['models/'] : []),
  ];
  const s3ArtifactPrefixes = manifest.s3ArtifactPrefixes?.length ? manifest.s3ArtifactPrefixes : defaultPrefixes;
  const allowedRegions = manifest.regions?.length ? manifest.regions : [...preset.compute.allowedRegions];
  const capabilities = [...preset.capabilities];
  if (manifest.hfAutoPublishPrefixes?.length && !capabilities.includes('hf_release')) {
    capabilities.push('hf_release');
  }
  if (manifest.trigger && !capabilities.includes('autonomy_triggers')) {
    capabilities.push('autonomy_triggers');
  }
  return {
    id,
    name: manifest.name,
    description: manifest.description ?? `${manifest.name} (hosted on HIVEMIND)`,
    template: manifest.template,
    capabilities,
    budget: {
      computeBudgetCapMicros,
      maxSingleJobCostMicros,
      maxDeliveryTaskBudgetMicros: preset.budget.maxDeliveryTaskBudgetMicros,
    },
    delivery: {
      repositories,
      autoMergeRepositories,
      defaultBranchPrefix: manifest.branchPrefix ?? preset.delivery.defaultBranchPrefix,
      defaultProtectedPaths: manifest.protectedPaths ?? [...preset.delivery.defaultProtectedPaths],
      allowAgentAccess: preset.delivery.allowAgentAccess,
      allowedWebHosts: [...preset.delivery.allowedWebHosts],
    },
    compute: {
      allowedRegions,
      s3ArtifactPrefixes,
      autoPublishHfRepoPrefixes: manifest.hfAutoPublishPrefixes ?? [],
      credentialPurposes: [...preset.compute.credentialPurposes],
      maxLifetimeMs: preset.compute.maxLifetimeMs,
    },
    ...(manifest.notificationChannel !== undefined ? { notificationChannel: manifest.notificationChannel } : {}),
  };
}

function renderMcpJson(hivemindRoot: string, tokenFile: string, apiUrl: string): string {
  return `${JSON.stringify(
    {
      mcpServers: {
        hivemind: {
          command: 'node',
          args: [join(hivemindRoot, 'dist/apps/mcp-server/src/main.js')],
          env: {
            HIVEMIND_MCP_PROFILE: 'project-agent',
            HIVEMIND_AGENT_TOKEN_FILE: tokenFile,
            HIVEMIND_API_URL: apiUrl,
          },
        },
      },
    },
    null,
    2,
  )}\n`;
}

function renderCodexToml(hivemindRoot: string, tokenFile: string, apiUrl: string): string {
  const esc = (v: string) => JSON.stringify(v);
  return [
    '# Generated by HIVEMIND project:bootstrap (project-agent profile)',
    '[mcp_servers.hivemind]',
    'command = "node"',
    `args = [${esc(join(hivemindRoot, 'dist/apps/mcp-server/src/main.js'))}]`,
    '',
    '[mcp_servers.hivemind.env]',
    'HIVEMIND_MCP_PROFILE = "project-agent"',
    `HIVEMIND_AGENT_TOKEN_FILE = ${esc(tokenFile)}`,
    `HIVEMIND_API_URL = ${esc(apiUrl)}`,
    '',
  ].join('\n');
}

function renderAutonomyStateJson(projectId: string): string {
  return `${JSON.stringify(
    {
      version: 1,
      projectId,
      stage: 'idle',
      cycle: 0,
      updatedAt: null,
      notes: 'Repository-owned autonomy state. Edit stage rules inside this repo; HIVEMIND triggers only advance one stage at a time.',
    },
    null,
    2,
  )}\n`;
}

function renderAutonomyCheckMjs(): string {
  return `import { readFileSync } from 'node:fs';\n\nconst state = JSON.parse(readFileSync('ops/autonomy/state.json', 'utf8'));\nif (state.version !== 1 || typeof state.projectId !== 'string' || !state.projectId) {\n  console.error('Invalid ops/autonomy/state.json');\n  process.exit(1);\n}\nconsole.log(JSON.stringify({ ok: true, projectId: state.projectId, stage: state.stage, cycle: state.cycle }));\n`;
}

function renderAutonomyReadme(projectId: string, name: string): string {
  return [
    `# ${name} — HIVEMIND 자율 루프 규칙`,
    '',
    `- 프로젝트 ID: \`${projectId}\``,
    '- 이 저장소가 자율 단계 상태(\`ops/autonomy/state.json\`)와 검증 스크립트(\`ops/autonomy/check.mjs\`)의 소유자입니다.',
    '- HIVEMIND 호스트의 주기 트리거는 열린 작업이 없을 때만 한 단계 진행 작업을 파견하며, 보호 경로(\`ops/autonomy/policy.json\` 등)를 건드린 변경은 자동 병합을 거절하고 트리거를 즉시 정지합니다.',
    '',
  ].join('\n');
}

async function apiRequest<T>(
  fetchImpl: typeof fetch,
  apiUrl: string,
  operatorToken: string,
  method: 'GET' | 'POST' | 'PATCH' | 'PUT',
  path: string,
  body?: unknown,
): Promise<{ status: number; data: T }> {
  const res = await fetchImpl(new URL(path, apiUrl), {
    method,
    redirect: 'error',
    headers: {
      authorization: `Bearer ${operatorToken}`,
      ...(body !== undefined ? { 'content-type': 'application/json' } : {}),
    },
    ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
    signal: AbortSignal.timeout(20_000),
  });
  const textBody = await res.text();
  const data = (textBody ? JSON.parse(textBody) : {}) as T;
  return { status: res.status, data };
}

export async function runProjectBootstrap(
  options: ProjectBootstrapOptions,
  system: ProjectBootstrapSystem,
): Promise<{ results: ProjectBootstrapStepResult[]; project?: ProjectPublicView; manualChecklist: string[] }> {
  const fetchImpl = system.fetchImpl ?? fetch;
  const results: ProjectBootstrapStepResult[] = [];
  const manualChecklist: string[] = [];
  const payload = buildCreateProjectPayload(options.manifest);
  const projectId = payload.id;

  results.push({
    step: '1. 매니페스트 검증',
    status: 'done',
    detail: `projectId=${projectId}, template=${payload.template}, budget=$${((payload.budget?.computeBudgetCapMicros ?? 0) / 1_000_000).toFixed(2)}, repos=${payload.delivery?.repositories?.join(', ') || '(없음)'}`,
  });

  let project: ProjectPublicView | undefined;
  if (options.dryRun) {
    results.push({
      step: '2. Control Plane 프로젝트 등록/갱신',
      status: 'planned',
      detail: `${options.apiUrl} 에 POST/PATCH /api/projects/${projectId} 수행 예정`,
    });
  } else {
    const existing = await apiRequest<Record<string, unknown>>(
      fetchImpl,
      options.apiUrl,
      options.operatorToken,
      'GET',
      `/api/projects/${encodeURIComponent(projectId)}`,
    );
    if (existing.status === 200) {
      const { id: _id, template: _tpl, ...updateBody } = payload;
      const updated = await apiRequest<ProjectPublicView>(
        fetchImpl,
        options.apiUrl,
        options.operatorToken,
        'PATCH',
        `/api/projects/${encodeURIComponent(projectId)}`,
        updateBody,
      );
      if (updated.status !== 200) {
        throw new Error(`프로젝트 갱신 실패 (HTTP ${updated.status}): ${JSON.stringify(updated.data)}`);
      }
      project = updated.data;
      results.push({
        step: '2. Control Plane 프로젝트 등록/갱신',
        status: 'done',
        detail: `기존 프로젝트 '${projectId}' 정책 갱신 완료`,
      });
    } else if (existing.status === 404) {
      const created = await apiRequest<ProjectPublicView>(
        fetchImpl,
        options.apiUrl,
        options.operatorToken,
        'POST',
        '/api/projects',
        payload,
      );
      if (created.status !== 201) {
        throw new Error(`프로젝트 등록 실패 (HTTP ${created.status}): ${JSON.stringify(created.data)}`);
      }
      project = created.data;
      results.push({
        step: '2. Control Plane 프로젝트 등록/갱신',
        status: 'done',
        detail: `새 프로젝트 '${projectId}' 등록 완료`,
      });
    } else {
      throw new Error(`Control Plane 프로젝트 조회 실패 (HTTP ${existing.status})`);
    }
  }

  // Step 3: Project-scoped agent token
  if (!options.issueToken && !options.rotateToken) {
    results.push({
      step: '3. 프로젝트 전용 에이전트 토큰',
      status: 'skipped',
      detail: '--issue-token 미지정으로 건너뜀',
    });
  } else if (system.fileExists(options.tokenOutputFile) && !options.rotateToken) {
    results.push({
      step: '3. 프로젝트 전용 에이전트 토큰',
      status: 'skipped',
      detail: `기존 토큰 파일 유지: ${options.tokenOutputFile} (재발급하려면 --rotate-token)`,
    });
  } else if (options.dryRun) {
    results.push({
      step: '3. 프로젝트 전용 에이전트 토큰',
      status: 'planned',
      detail: `POST /api/projects/${projectId}/tokens 호출 후 ${options.tokenOutputFile} (0600) 저장 예정`,
    });
  } else {
    const issued = await apiRequest<IssuedProjectToken>(
      fetchImpl,
      options.apiUrl,
      options.operatorToken,
      'POST',
      `/api/projects/${encodeURIComponent(projectId)}/tokens`,
      { label: options.rotateToken ? `bootstrap-rotated-${Date.now()}` : 'bootstrap-default' },
    );
    if (issued.status !== 201 || !issued.data?.token) {
      throw new Error(`프로젝트 토큰 발급 실패 (HTTP ${issued.status})`);
    }
    const secretJson = `${JSON.stringify({ PROJECT_ID: projectId, AGENT_TOKEN: issued.data.token, TOKEN_ID: issued.data.metadata.tokenId }, null, 2)}\n`;
    system.writeSecretFile(options.tokenOutputFile, secretJson);
    results.push({
      step: '3. 프로젝트 전용 에이전트 토큰',
      status: 'done',
      detail: `토큰(${issued.data.metadata.tokenPrefix}…) 발급 및 0600 저장 완료: ${options.tokenOutputFile} (화면 미출력)`,
    });
  }

  // Step 4: Optional Autonomy Trigger (always created disabled for safety)
  if (!options.withTrigger) {
    results.push({
      step: '4. 주기 자율 트리거 등록',
      status: 'skipped',
      detail: '--with-trigger 미지정으로 건너뜀',
    });
  } else if (!payload.delivery?.repositories?.length) {
    results.push({
      step: '4. 주기 자율 트리거 등록',
      status: 'warning',
      detail: '대상 GitHub 저장소(--repo)가 없어 트리거 등록을 건너뛰었습니다.',
    });
  } else {
    const triggerId = `${projectId}-loop`;
    const repo = payload.delivery.repositories[0]!;
    const triggerCfg = {
      projectId,
      repository: repo,
      baseBranch: options.manifest.trigger?.baseBranch ?? 'main',
      branchPrefix: payload.delivery.defaultBranchPrefix ?? 'agent/',
      title: options.manifest.trigger?.title ?? `${payload.name} — 자율 단계 진행`,
      instructions:
        options.manifest.trigger?.instructions ??
        'ops/autonomy/state.json 을 읽고 현재 단계의 작업 1건을 완수한 뒤 상태와 검증 결과를 갱신하세요.',
      provider: options.manifest.trigger?.provider ?? 'codex',
      intervalMinutes: options.manifest.trigger?.intervalMinutes ?? 60,
      maxIterations: 2,
      maxIterationDurationMs: 1_800_000,
      budgetMicros: Math.min(payload.budget?.maxDeliveryTaskBudgetMicros ?? 25_000_000, 25_000_000),
      protectedPaths: payload.delivery.defaultProtectedPaths?.length
        ? payload.delivery.defaultProtectedPaths
        : ['ops/autonomy/policy.json'],
      testCommand: options.manifest.trigger?.testCommand ?? ['node', 'ops/autonomy/check.mjs'],
    };
    if (options.dryRun) {
      results.push({
        step: '4. 주기 자율 트리거 등록',
        status: 'planned',
        detail: `PUT /api/autonomy/triggers/${triggerId} (비활성 상태로 생성 예정, repo=${repo})`,
      });
    } else {
      const trigRes = await apiRequest<Record<string, unknown>>(
        fetchImpl,
        options.apiUrl,
        options.operatorToken,
        'PUT',
        `/api/autonomy/triggers/${encodeURIComponent(triggerId)}`,
        triggerCfg,
      );
      if (trigRes.status !== 200) {
        throw new Error(`트리거 등록 실패 (HTTP ${trigRes.status}): ${JSON.stringify(trigRes.data)}`);
      }
      results.push({
        step: '4. 주기 자율 트리거 등록',
        status: 'done',
        detail: `트리거 '${triggerId}' 등록 완료 (안전상 꺼짐 상태 — 준비 후 /enable 로 활성화)`,
      });
    }
  }

  // Step 5: Optional Target Repo Scaffolding
  if (!options.targetDir) {
    results.push({
      step: '5. 대상 저장소 스캐폴딩',
      status: 'skipped',
      detail: '--target-dir 미지정으로 건너뜀',
    });
  } else {
    const root = resolve(options.targetDir);
    const files: Array<{ rel: string; content: string }> = [
      {
        rel: 'hivemind.project.json',
        content: `${JSON.stringify(
          {
            schemaVersion: 1,
            id: projectId,
            name: payload.name,
            description: payload.description,
            template: payload.template,
            repositories: payload.delivery?.repositories ?? [],
            autoMerge: Boolean(options.manifest.autoMerge),
            budgetUsd: (payload.budget?.computeBudgetCapMicros ?? 0) / 1_000_000,
            ...(payload.budget?.maxSingleJobCostMicros ? { maxJobUsd: payload.budget.maxSingleJobCostMicros / 1_000_000 } : {}),
            regions: payload.compute?.allowedRegions ?? [],
            s3ArtifactPrefixes: payload.compute?.s3ArtifactPrefixes ?? [],
            ...(payload.compute?.autoPublishHfRepoPrefixes?.length ? { hfAutoPublishPrefixes: payload.compute.autoPublishHfRepoPrefixes } : {}),
            protectedPaths: payload.delivery?.defaultProtectedPaths ?? [],
            branchPrefix: payload.delivery?.defaultBranchPrefix ?? 'agent/',
          },
          null,
          2,
        )}\n`,
      },
      { rel: '.mcp.json', content: renderMcpJson(options.hivemindRoot, options.tokenOutputFile, options.apiUrl) },
      { rel: '.codex/config.toml', content: renderCodexToml(options.hivemindRoot, options.tokenOutputFile, options.apiUrl) },
    ];
    if (options.withTrigger) {
      files.push(
        { rel: 'ops/autonomy/state.json', content: renderAutonomyStateJson(projectId) },
        { rel: 'ops/autonomy/check.mjs', content: renderAutonomyCheckMjs() },
        { rel: 'ops/autonomy/README.md', content: renderAutonomyReadme(projectId, payload.name) },
      );
    }
    const written: string[] = [];
    const skipped: string[] = [];
    for (const f of files) {
      const full = join(root, f.rel);
      if (system.fileExists(full) && !options.force) {
        skipped.push(f.rel);
        continue;
      }
      if (!options.dryRun) {
        system.writeFile(full, f.content);
      }
      written.push(f.rel);
    }
    results.push({
      step: '5. 대상 저장소 스캐폴딩',
      status: options.dryRun ? 'planned' : 'done',
      detail: `${options.dryRun ? '생성 예정' : '작성'}: ${written.join(', ') || '없음'}${skipped.length ? ` (기존 파일 보존: ${skipped.join(', ')})` : ''}`,
    });
  }

  // Manual web checklist (things automation cannot do for you)
  for (const repo of payload.delivery?.repositories ?? []) {
    manualChecklist.push(`GitHub App 설치 대상에 저장소 '${repo}' 가 포함되어 있는지 확인 (미포함 시 GitHub 웹 설정에서 추가)`);
  }
  if (payload.capabilities?.includes('hf_release')) {
    manualChecklist.push('Hugging Face 공개를 사용하는 경우, Control Plane Secrets Manager의 HF 토큰이 대상 조직 쓰기 권한을 갖는지 확인');
  }
  if (options.withTrigger) {
    manualChecklist.push(`저장소에 ops/autonomy/* 파일을 커밋한 뒤 운영자 권한으로 트리거 '${projectId}-loop' 를 활성화(/api/autonomy/triggers/${projectId}-loop/enable)`);
  }

  return { results, ...(project ? { project } : {}), manualChecklist };
}

export function formatProjectBootstrapReport(
  results: ProjectBootstrapStepResult[],
  manualChecklist: string[],
): string {
  const lines = ['=== HIVEMIND 프로젝트 부트스트랩 보고 ==='];
  for (const r of results) {
    lines.push(`[${r.status.toUpperCase()}] ${r.step} — ${r.detail}`);
  }
  if (manualChecklist.length > 0) {
    lines.push('', '사람이 확인·수행할 체크리스트:');
    for (const item of manualChecklist) {
      lines.push(`  - ${item}`);
    }
  }
  return lines.join('\n');
}

